/**
 * Generates PostgreSQL DDL for the Prisma schema from Prisma's own parser (DMMF),
 * following Prisma Migrate's naming conventions (<table>_pkey, <table>_<cols>_key, _idx, _fkey).
 *
 * Why: the planning/build sandbox cannot download Prisma's native schema-engine (binaries.prisma.sh
 * is blocked), so `prisma migrate dev/diff` cannot run there. CI (GitHub Actions) runs
 * `prisma migrate diff --from-migrations --to-schema` with the real engine to prove there is no drift
 * (see .github/workflows/ci.yml). Recorded in documentation/DECISIONS.md (D-12).
 *
 * Usage: tsx packages/database/scripts/baseline-sql.ts > packages/database/prisma/migrations/<name>/migration.sql
 */
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const { getDMMF } = require('@prisma/internals') as typeof import('@prisma/internals');

type Field = {
  name: string; dbName?: string | null; kind: 'scalar' | 'object' | 'enum' | 'unsupported'; type: string;
  isList: boolean; isRequired: boolean; isId: boolean; isUnique: boolean; isUpdatedAt: boolean;
  hasDefaultValue: boolean; default?: unknown; nativeType?: [string, string[]] | null;
  relationFromFields?: string[]; relationToFields?: string[]; relationOnDelete?: string;
};
type Model = { name: string; dbName: string | null; fields: Field[]; primaryKey: { fields: string[] } | null };

const q = (s: string) => `"${s}"`;
const lit = (v: unknown) => (typeof v === 'string' ? `'${v.replace(/'/g, "''")}'` : String(v));
const trunc = (n: string) => (n.length > 63 ? n.slice(0, 63) : n);

function colType(f: Field, enums: Set<string>): string {
  let t: string;
  if (f.kind === 'enum' || enums.has(f.type)) t = q(f.type);
  else if (f.nativeType) {
    const [nt, args] = f.nativeType;
    t = nt.toUpperCase() + (args?.length ? `(${args.join(',')})` : '');
  } else {
    t = ({ String: 'TEXT', Int: 'INTEGER', BigInt: 'BIGINT', Float: 'DOUBLE PRECISION', Decimal: 'DECIMAL(65,30)',
      Boolean: 'BOOLEAN', DateTime: 'TIMESTAMP(3)', Json: 'JSONB', Bytes: 'BYTEA' } as Record<string, string>)[f.type];
    if (!t) throw new Error(`Unsupported type ${f.type} on ${f.name}`);
  }
  return f.isList ? `${t}[]` : t;
}

function defaultClause(f: Field): string {
  if (!f.hasDefaultValue || f.default === undefined) return '';
  const d = f.default as { name?: string; args?: unknown[] } | string | number | boolean | unknown[];
  if (typeof d === 'object' && d !== null && !Array.isArray(d) && 'name' in d) {
    if (d.name === 'now') return ' DEFAULT CURRENT_TIMESTAMP';
    if (d.name === 'autoincrement') return '';
    if (d.name === 'dbgenerated') return ` DEFAULT ${String(d.args?.[0])}`;
    return ''; // cuid()/uuid() are generated by Prisma Client
  }
  if (Array.isArray(d)) return ` DEFAULT ARRAY[${d.map(lit).join(', ')}]`;
  return ` DEFAULT ${lit(d)}`;
}

export async function baselineSql(schemaPath: string): Promise<string> {
  const dmmf = await getDMMF({ datamodel: readFileSync(schemaPath, 'utf8') });
  const enums = new Set(dmmf.datamodel.enums.map((e) => e.name));
  const models = dmmf.datamodel.models as unknown as Model[];
  const table = (m: Model) => m.dbName ?? m.name;
  const col = (m: Model, name: string) => m.fields.find((f) => f.name === name)?.dbName ?? name;
  const out: string[] = [];

  for (const e of dmmf.datamodel.enums) {
    out.push(`-- CreateEnum\nCREATE TYPE ${q(e.name)} AS ENUM (${e.values.map((v) => lit(v.dbName ?? v.name)).join(', ')});\n`);
  }

  for (const m of models) {
    const lines: string[] = [];
    for (const f of m.fields) {
      if (f.kind === 'object') continue;
      const serial = (f.default as { name?: string } | undefined)?.name === 'autoincrement';
      const type = serial ? (f.type === 'BigInt' ? 'BIGSERIAL' : 'SERIAL') : colType(f, enums);
      lines.push(`    ${q(f.dbName ?? f.name)} ${type}${f.isRequired ? ' NOT NULL' : ''}${defaultClause(f)}`);
    }
    const pk = m.primaryKey?.fields ?? m.fields.filter((f) => f.isId).map((f) => f.name);
    lines.push(`    CONSTRAINT ${q(trunc(`${table(m)}_pkey`))} PRIMARY KEY (${pk.map((n) => q(col(m, n))).join(',')})`);
    out.push(`-- CreateTable\nCREATE TABLE ${q(table(m))} (\n${lines.join(',\n')}\n);\n`);
  }

  for (const idx of dmmf.datamodel.indexes as unknown as Array<{ model: string; type: string; fields: { name: string }[]; dbName?: string; name?: string }>) {
    if (idx.type === 'id') continue;
    const m = models.find((x) => x.name === idx.model)!;
    const cols = idx.fields.map((f) => col(m, f.name));
    const suffix = idx.type === 'unique' ? 'key' : 'idx';
    const name = idx.dbName ?? trunc(`${table(m)}_${cols.join('_')}_${suffix}`);
    out.push(`-- CreateIndex\nCREATE ${idx.type === 'unique' ? 'UNIQUE ' : ''}INDEX ${q(name)} ON ${q(table(m))}(${cols.map(q).join(', ')});\n`);
  }

  for (const m of models) {
    for (const f of m.fields) {
      if (f.kind !== 'object' || !f.relationFromFields?.length) continue;
      const target = models.find((x) => x.name === f.type)!;
      const from = f.relationFromFields.map((n) => col(m, n));
      const to = (f.relationToFields ?? []).map((n) => col(target, n));
      const optional = f.relationFromFields.some((n) => !m.fields.find((x) => x.name === n)!.isRequired);
      const onDelete = ({ Cascade: 'CASCADE', Restrict: 'RESTRICT', SetNull: 'SET NULL', NoAction: 'NO ACTION', SetDefault: 'SET DEFAULT' } as Record<string, string>)[
        f.relationOnDelete ?? (optional ? 'SetNull' : 'Restrict')
      ];
      out.push(
        `-- AddForeignKey\nALTER TABLE ${q(table(m))} ADD CONSTRAINT ${q(trunc(`${table(m)}_${from.join('_')}_fkey`))} FOREIGN KEY (${from.map(q).join(', ')}) REFERENCES ${q(table(target))}(${to.map(q).join(', ')}) ON DELETE ${onDelete} ON UPDATE CASCADE;\n`,
      );
    }
  }
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const schema = process.argv[2] ?? path.join(import.meta.dirname, '..', 'prisma', 'schema.prisma');
  baselineSql(schema).then((sql) => process.stdout.write(sql));
}
